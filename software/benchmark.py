"""
NEXORA Software Performance Benchmarking Tool
Measures latencies, memory footprint, CPU utilization, energy proxy,
and downstream edge intent & action latencies.

IMPORTANT NOTE:
All metrics generated by this script are SOFTWARE MEASUREMENTS executed on
the host laptop CPU (x86_64). They are NOT ESP32 hardware measurements.
Hardware metrics on the ESP32-S3 will differ based on CPU frequency (240MHz)
and ESP-NN vector extensions.
"""

import os
import sys
import time
import json
import tracemalloc
import numpy as np
from pathlib import Path

# Add project root to path
BASE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE_DIR))

from software.app import config
from software.app.features import FeatureExtractor
from software.app.kws import NexoraKWS
from software.app.temporal import TemporalVerifier
from software.app.asr import LocalASREngine
from software.app.intent import IntentGatekeeper
from software.app.actions import ActionExecutor
from software.app.adaptive import AcousticContextEstimator, AdaptivePolicy

try:
    import psutil
    PSUTIL_AVAILABLE = True
except ImportError:
    PSUTIL_AVAILABLE = False


def run_benchmark(num_iterations: int = 100, output_path: Path = config.LOGS_DIR / "benchmark_report.json"):
    print("=" * 65)
    print(" NEXORA SOFTWARE PERFORMANCE BENCHMARK")
    print(" Target: Laptop Host CPU (Software Baseline Measurement)")
    print("=" * 65)

    tracemalloc.start()
    proc = psutil.Process(os.getpid()) if PSUTIL_AVAILABLE else None

    fe = FeatureExtractor()
    kws = NexoraKWS()
    temporal = TemporalVerifier()
    asr = LocalASREngine()
    intent_gate = IntentGatekeeper()
    actions = ActionExecutor()

    # Generate synthetic 16 kHz audio buffer for standard benchmark
    sample_rate = config.SAMPLE_RATE
    dummy_audio = np.random.uniform(-0.5, 0.5, sample_rate).astype(np.float32)

    # Warm-up runs
    for _ in range(5):
        f = fe.extract_features(dummy_audio)
        if kws.is_loaded:
            _ = kws.model.predict_proba(f.reshape(1, -1))
        _ = intent_gate.classify("turn on the lights")
        _ = actions.execute("LIGHT_ON")

    # 1. Benchmark Feature Extraction
    feature_latencies = []
    for _ in range(num_iterations):
        t0 = time.perf_counter()
        _ = fe.extract_features(dummy_audio, flatten=True)
        t1 = time.perf_counter()
        feature_latencies.append((t1 - t0) * 1000.0)

    # 2. Benchmark Model Inference
    features = fe.extract_features(dummy_audio, flatten=True).reshape(1, -1)
    inference_latencies = []
    if kws.is_loaded and kws.model is not None:
        for _ in range(num_iterations):
            t0 = time.perf_counter()
            _ = kws.model.predict_proba(features)
            t1 = time.perf_counter()
            inference_latencies.append((t1 - t0) * 1000.0)
    else:
        inference_latencies = [0.0]

    # 3. Benchmark Temporal Verification
    temporal_latencies = []
    for _ in range(num_iterations):
        t0 = time.perf_counter()
        _, _, _ = temporal.update(0.85)
        t1 = time.perf_counter()
        temporal_latencies.append((t1 - t0) * 1000.0)

    # 4. Total Pipeline Latency & CPU Workload
    if proc:
        proc.cpu_percent(interval=None)
    cpu_clock_start = time.process_time()
    wall_clock_start = time.perf_counter()

    total_latencies = []
    for _ in range(num_iterations):
        t0 = time.perf_counter()
        feats = fe.extract_features(dummy_audio, flatten=True)
        if kws.is_loaded:
            probs = kws.model.predict_proba(feats.reshape(1, -1))[0]
            score = probs[config.CLASS_TO_IDX["NEXORA"]]
        else:
            score = 0.0
        _, _, _ = temporal.update(score)
        t1 = time.perf_counter()
        total_latencies.append((t1 - t0) * 1000.0)

    wall_duration = time.perf_counter() - wall_clock_start
    total_cpu_time = time.process_time() - cpu_clock_start
    proc_cpu_pct = proc.cpu_percent(interval=None) if proc else (total_cpu_time / (wall_duration + 1e-8)) * 100.0

    # 5. Measure ASR Latency on 2.0s audio
    dummy_cmd = np.zeros(sample_rate * 2, dtype=np.float32)
    t0 = time.perf_counter()
    asr_res = asr.transcribe(dummy_cmd)
    asr_latency_ms = (time.perf_counter() - t0) * 1000.0

    # 6. Benchmark Intent Classification Latency
    intent_latencies = []
    sample_phrase = "turn on the lights"
    for _ in range(num_iterations):
        t0 = time.perf_counter()
        _ = intent_gate.classify(sample_phrase)
        t1 = time.perf_counter()
        intent_latencies.append((t1 - t0) * 1000.0)

    # 7. Benchmark Action Execution Latency
    action_latencies = []
    for _ in range(num_iterations):
        t0 = time.perf_counter()
        _ = actions.execute("LIGHT_ON")
        t1 = time.perf_counter()
        action_latencies.append((t1 - t0) * 1000.0)

    # 8. Benchmark Context Estimator & Adaptive Policy Latency
    estimator = AcousticContextEstimator()
    policy = AdaptivePolicy()
    context_estimator_latencies = []
    policy_latencies = []
    for _ in range(num_iterations):
        t0 = time.perf_counter()
        ctx = estimator.estimate_context(dummy_audio)
        t1 = time.perf_counter()
        dec = policy.should_evaluate(ctx, current_time=t1)
        t2 = time.perf_counter()
        context_estimator_latencies.append((t1 - t0) * 1000.0)
        policy_latencies.append((t2 - t1) * 1000.0)

    # 9. Comparative Simulated Stream Benchmark (100 windows: 80% quiet, 20% active)
    stream_windows = 100
    quiet_window = np.zeros(sample_rate, dtype=np.float32)
    active_window = dummy_audio

    # Test stream: 40 quiet, 20 active, 40 quiet
    test_stream = [quiet_window] * 40 + [active_window] * 20 + [quiet_window] * 40

    # Baseline run
    baseline_evals = 0
    t_start_base = time.perf_counter()
    for w in test_stream:
        f = fe.extract_features(w, flatten=True)
        if kws.is_loaded:
            _ = kws.model.predict_proba(f.reshape(1, -1))
        baseline_evals += 1
    baseline_compute_ms = (time.perf_counter() - t_start_base) * 1000.0

    # Adaptive run
    adaptive_estimator = AcousticContextEstimator()
    adaptive_policy = AdaptivePolicy(max_kws_gap_ms=config.MAX_KWS_GAP_MS)
    adaptive_evals = 0
    adaptive_skips = 0
    t_start_adapt = time.perf_counter()
    for i, w in enumerate(test_stream):
        sim_time = i * config.STEP_DURATION_SEC
        c = adaptive_estimator.estimate_context(w)
        d = adaptive_policy.should_evaluate(c, current_time=sim_time)
        if d.should_evaluate:
            f = fe.extract_features(w, flatten=True)
            if kws.is_loaded:
                _ = kws.model.predict_proba(f.reshape(1, -1))
            adaptive_evals += 1
        else:
            adaptive_skips += 1
    adaptive_compute_ms = (time.perf_counter() - t_start_adapt) * 1000.0
    adaptive_skip_rate = (adaptive_skips / stream_windows) * 100.0

    # Post-ASR Total Latency
    mean_intent_ms = float(np.mean(intent_latencies))
    mean_action_ms = float(np.mean(action_latencies))
    total_post_asr_ms = mean_intent_ms + mean_action_ms

    # Memory and Model size
    current_mem, peak_mem = tracemalloc.get_traced_memory()
    tracemalloc.stop()

    model_size_bytes = os.path.getsize(str(config.MODEL_PATH)) if config.MODEL_PATH.exists() else 0
    rss_mb = (proc.memory_info().rss / (1024.0 * 1024.0)) if proc else (peak_mem / (1024.0 * 1024.0))

    # Energy Proxy Calculations (Standard TinyML Duty Cycle Metric)
    step_interval_ms = config.STEP_DURATION_SEC * 1000.0
    mean_kws_latency = float(np.mean(total_latencies))
    duty_cycle_pct = (mean_kws_latency / step_interval_ms) * 100.0
    cpu_time_per_window_ms = (total_cpu_time / num_iterations) * 1000.0

    results = {
        "benchmark_environment": "SOFTWARE MEASUREMENT (Host Laptop PC)",
        "iterations": num_iterations,
        "sample_rate_hz": config.SAMPLE_RATE,
        "window_duration_sec": config.WINDOW_DURATION_SEC,
        "step_interval_sec": config.STEP_DURATION_SEC,
        "feature_extraction_latency_ms": {
            "mean": float(np.mean(feature_latencies)),
            "std": float(np.std(feature_latencies)),
            "min": float(np.min(feature_latencies)),
            "max": float(np.max(feature_latencies)),
            "p95": float(np.percentile(feature_latencies, 95))
        },
        "model_inference_latency_ms": {
            "mean": float(np.mean(inference_latencies)),
            "std": float(np.std(inference_latencies)),
            "min": float(np.min(inference_latencies)),
            "max": float(np.max(inference_latencies)),
            "p95": float(np.percentile(inference_latencies, 95))
        },
        "temporal_verification_latency_ms": {
            "mean": float(np.mean(temporal_latencies)),
            "min": float(np.min(temporal_latencies)),
            "max": float(np.max(temporal_latencies))
        },
        "total_local_detection_latency_ms": {
            "mean": mean_kws_latency,
            "std": float(np.std(total_latencies)),
            "min": float(np.min(total_latencies)),
            "max": float(np.max(total_latencies)),
            "p95": float(np.percentile(total_latencies, 95))
        },
        "local_asr_latency_ms": float(asr_latency_ms),
        "intent_classification_latency_ms": {
            "mean": mean_intent_ms,
            "std": float(np.std(intent_latencies)),
            "min": float(np.min(intent_latencies)),
            "max": float(np.max(intent_latencies)),
            "p95": float(np.percentile(intent_latencies, 95))
        },
        "action_execution_latency_ms": {
            "mean": mean_action_ms,
            "std": float(np.std(action_latencies)),
            "min": float(np.min(action_latencies)),
            "max": float(np.max(action_latencies)),
            "p95": float(np.percentile(action_latencies, 95))
        },
        "total_post_asr_latency_ms": total_post_asr_ms,
        "adaptive_controller_metrics": {
            "context_estimator_latency_ms": {
                "mean": float(np.mean(context_estimator_latencies)),
                "std": float(np.std(context_estimator_latencies)),
                "p95": float(np.percentile(context_estimator_latencies, 95))
            },
            "policy_decision_latency_ms": {
                "mean": float(np.mean(policy_latencies)),
                "std": float(np.std(policy_latencies)),
                "p95": float(np.percentile(policy_latencies, 95))
            },
            "comparative_stream_100_windows": {
                "total_windows": stream_windows,
                "baseline_evaluations": baseline_evals,
                "baseline_compute_ms": float(baseline_compute_ms),
                "adaptive_evaluations": adaptive_evals,
                "adaptive_skips": adaptive_skips,
                "adaptive_skip_rate_pct": float(adaptive_skip_rate),
                "adaptive_compute_ms": float(adaptive_compute_ms),
                "compute_reduction_pct": float((1.0 - adaptive_compute_ms / max(1e-5, baseline_compute_ms)) * 100.0)
            }
        },
        "model_storage_size_bytes": int(model_size_bytes),
        "model_storage_size_kb": float(model_size_bytes / 1024.0),
        "memory_usage": {
            "process_rss_mb": float(rss_mb),
            "heap_peak_traced_mb": float(peak_mem / (1024.0 * 1024.0))
        },
        "cpu_usage": {
            "measured_process_cpu_percent": float(proc_cpu_pct),
            "cpu_time_per_inference_window_ms": float(cpu_time_per_window_ms)
        },
        "energy_proxy": {
            "metric_type": "Active Inference Duty Cycle & CPU Execution Time",
            "active_duty_cycle_percent": float(duty_cycle_pct),
            "idle_sleep_capacity_percent": float(100.0 - duty_cycle_pct),
            "step_interval_ms": step_interval_ms,
            "notes": (
                "Duty cycle represents the proportion of time the CPU is actively processing KWS. "
                "Physical power/energy (milliwatts/Joules) cannot be measured without hardware current shunt "
                "or digital power analyzer; active duty cycle is the recognized embedded proxy."
            )
        },
        "disclaimer": "SOFTWARE MEASUREMENTS ONLY. NOT applicable to ESP32-S3 hardware without on-target measurement."
    }

    # Print summary
    print(f"\n--- SOFTWARE PERFORMANCE RESULTS ({num_iterations} Iterations) ---")
    print(f"Feature Extraction Latency (Mean) : {results['feature_extraction_latency_ms']['mean']:.2f} ms")
    print(f"Model Inference Latency (Mean)    : {results['model_inference_latency_ms']['mean']:.2f} ms")
    print(f"Temporal Verification Latency     : {results['temporal_verification_latency_ms']['mean']:.4f} ms")
    print(f"Total Local KWS Latency (Mean)    : {results['total_local_detection_latency_ms']['mean']:.2f} ms")
    print(f"Context Estimator Latency (Mean)  : {results['adaptive_controller_metrics']['context_estimator_latency_ms']['mean']:.4f} ms")
    print(f"Adaptive Policy Latency (Mean)    : {results['adaptive_controller_metrics']['policy_decision_latency_ms']['mean']:.4f} ms")
    print(f"Local ASR Latency (2.0s audio)    : {results['local_asr_latency_ms']:.2f} ms")
    print(f"Intent Classification Latency     : {results['intent_classification_latency_ms']['mean']:.3f} ms")
    print(f"Action Execution Latency          : {results['action_execution_latency_ms']['mean']:.3f} ms")
    print(f"Total Post-ASR Latency (Mean)     : {results['total_post_asr_latency_ms']:.3f} ms")
    print(f"KWS Model File Size               : {results['model_storage_size_kb']:.2f} KB")
    print(f"Process RAM (Resident Set Size)   : {results['memory_usage']['process_rss_mb']:.2f} MB")
    print(f"Process CPU Utilization           : {results['cpu_usage']['measured_process_cpu_percent']:.1f}%")
    print(f"Energy Proxy (Active Duty Cycle)  : {results['energy_proxy']['active_duty_cycle_percent']:.2f}% (Idle/Sleep: {results['energy_proxy']['idle_sleep_capacity_percent']:.2f}%)")
    print("-" * 65)
    print(" [ADAPTIVE VS BASELINE STREAM COMPARISON (100 Windows)]")
    stream_res = results['adaptive_controller_metrics']['comparative_stream_100_windows']
    print(f" Baseline Evals: {stream_res['baseline_evaluations']} | Compute Time: {stream_res['baseline_compute_ms']:.2f} ms")
    print(f" Adaptive Evals: {stream_res['adaptive_evaluations']} | Skipped: {stream_res['adaptive_skips']} ({stream_res['adaptive_skip_rate_pct']:.1f}%) | Compute Time: {stream_res['adaptive_compute_ms']:.2f} ms")
    print(f" Host Compute Reduction           : {stream_res['compute_reduction_pct']:.1f}%")
    print("=" * 65)

    with open(output_path, "w") as f:
        json.dump(results, f, indent=2)

    print(f"[OK] Full benchmark report saved to: {output_path}")
    return results


if __name__ == "__main__":
    run_benchmark()
